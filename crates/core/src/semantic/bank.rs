/// Отпечаток списка: другой список — другие векторы мерки.
pub fn fingerprint() -> u64 {
    fnv(QUERIES.join("\n").as_bytes())
}

const MAGIC: &[u8; 8] = b"MHBANK1\n";

/// Векторы мерки — на диск: с ними второй запуск не ждёт модель. `key` — модель и
/// [`fingerprint`]: другая модель или другой список — векторы не подходят.
pub fn write(key: &str, vectors: &[Vec<f32>]) -> Vec<u8> {
    let mut out = MAGIC.to_vec();
    out.extend_from_slice(&(key.len() as u32).to_le_bytes());
    out.extend_from_slice(key.as_bytes());
    out.extend_from_slice(&(vectors.len() as u32).to_le_bytes());
    for vector in vectors {
        for value in vector.iter().take(DIMS) {
            out.extend_from_slice(&value.to_le_bytes());
        }
    }
    let checksum = fnv(&out);
    out.extend_from_slice(&checksum.to_le_bytes());
    out
}

/// Прочитать сохранённые векторы, если они для того же `key` и целы.
pub fn read(bytes: &[u8], key: &str) -> Option<Vec<Vec<f32>>> {
    let (payload, tail) = bytes.split_at_checked(bytes.len().checked_sub(8)?)?;
    if !payload.starts_with(MAGIC) || fnv(payload) != u64::from_le_bytes(tail.try_into().ok()?) {
        return None;
    }
    let mut reader = Reader { bytes: payload, at: MAGIC.len() };
    let len = reader.u32()? as usize;
    if reader.take(len)? != key.as_bytes() {
        return None;
    }
    let count = reader.u32()? as usize;
    let mut vectors = Vec::with_capacity(count.min(4096));
    for _ in 0..count {
        let raw = reader.take(DIMS * 4)?;
        vectors.push(raw.as_chunks::<4>().0.iter().map(|b| f32::from_le_bytes(*b)).collect());
    }
    (reader.at == payload.len()).then_some(vectors)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vectors_round_trip_for_the_same_key_only() {
        let vectors = vec![vec![0.5f32; DIMS], vec![-0.25f32; DIMS]];
        let bytes = write("model|ff", &vectors);
        assert_eq!(read(&bytes, "model|ff"), Some(vectors));
        assert_eq!(read(&bytes, "model|00"), None);
        let mut broken = bytes.clone();
        broken[20] ^= 1;
        assert_eq!(read(&broken, "model|ff"), None);
        assert_eq!(read(&bytes[..3], "model|ff"), None);
    }

    #[test]
    fn queries_are_distinct_and_plain() {
        let mut seen = std::collections::HashSet::new();
        for query in QUERIES {
            assert!(seen.insert(*query), "повтор: {query}");
            assert_eq!(query.trim(), *query);
        }
        assert!(QUERIES.len() >= 150);
        assert_ne!(fingerprint(), 0);
    }
}
