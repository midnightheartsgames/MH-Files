//! картинки с надписями, файлы без содержимого; 12 запросов): при пороге 3 — 163 верных из
//! 207 и 15 неверных (почти все — спорная разметка: мотокросс на «мотоцикл», планёр на
//! «самолёт»); прежний отбор по выделению среди остальных файлов — 172 верных и 135 неверных.
