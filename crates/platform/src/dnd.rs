//! Перетаскивание из MH Files в другие программы (OLE `DoDragDrop`).
//!
//! Исключение из правила «никакого Shell в потоке UI»: `DoDragDrop` обязан идти в потоке,
//! который получает ввод мыши, и сам крутит цикл сообщений, пока пользователь не отпустит
//! кнопку. Это действие пользователя, а не ожидание диска: окно не «висит», оно тащит.

use std::path::PathBuf;

/// Чем кончилось перетаскивание.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DropEffect {
    /// Отпустили там, где принять нельзя, или нажали Esc.
    None,
    Copy,
    /// Получатель переместил файлы — список нужно перечитать.
    Move,
    Link,
}

/// Начать перетаскивание файлов наружу. Кнопка мыши должна быть нажата.
pub fn drag_out(paths: &[PathBuf]) -> Result<DropEffect, String> {
    #[cfg(windows)]
    {
        crate::win::dnd::drag_out(paths)
    }
    #[cfg(not(windows))]
    {
        let _ = paths;
        Err("перетаскивание в другие программы есть только в Windows".into())
    }
}
